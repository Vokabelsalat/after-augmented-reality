// Compiles the exported constellation PNGs into public/targets/exhibition.mind
// with MindAR's offline compiler. Only the -white targets are compiled, in
// exhibitionId order, so MindAR index N is the artifact with targetIndex N.
//
// Next to the bundle it writes Brotli and gzip copies, which /api/targets
// serves to browsers that accept them, and the bundle's content hash to
// src/data/targetBundle.ts, which versions the URL so browsers cache it.
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { brotliCompressSync, constants, gzipSync } from "node:zlib";
import { loadImage } from "canvas";
import { OfflineCompiler } from "mind-ar/src/image-target/offline-compiler.js";
import { artifacts } from "../src/data/artifacts.ts";

const ordered = [...artifacts].sort((a, b) => a.targetIndex - b.targetIndex);
const sources = ordered.map((artifact) => ({
  artifact,
  file: `public/targets/${artifact.exhibitionId}-${artifact.id}-white.png`,
}));
const images = await Promise.all(sources.map(({ file }) => loadImage(file)));

const compiler = new OfflineCompiler();
let reported = -10;
const data = await compiler.compileImageTargets(images, (percent) => {
  if (percent - reported < 10) return;
  reported = percent;
  console.log(`compiling ${Math.round(percent)}%`);
});

data.forEach(({ trackingData }, index) => {
  const points = trackingData.map(({ points }) => points.length).join("/");
  console.log(`target ${index} ${sources[index].file}: tracking points ${points}`);
});

const bundle = Buffer.from(compiler.exportData());
const brotli = brotliCompressSync(bundle, {
  params: { [constants.BROTLI_PARAM_QUALITY]: 11, [constants.BROTLI_PARAM_SIZE_HINT]: bundle.length },
});
const gzip = gzipSync(bundle, { level: 9 });
const version = createHash("sha256").update(bundle).digest("hex").slice(0, 12);
writeFileSync("public/targets/exhibition.mind", bundle);
writeFileSync("public/targets/exhibition.mind.br", brotli);
writeFileSync("public/targets/exhibition.mind.gz", gzip);
writeFileSync(
  "src/data/targetBundle.ts",
  `// Generated by scripts/compile-mind-targets.mjs. The hash of
// public/targets/exhibition.mind versions its URL, so browsers can cache it.
export const targetBundleVersion = "${version}";
`,
);
const kilobytes = (buffer) => `${Math.round(buffer.length / 1024)} KB`;
console.log(
  `wrote public/targets/exhibition.mind (${kilobytes(bundle)}, brotli ${kilobytes(brotli)}, gzip ${kilobytes(gzip)}), version ${version}`,
);
